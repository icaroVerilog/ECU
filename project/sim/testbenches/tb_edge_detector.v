`timescale 1ns/1ps

module tb_edge_detector;

    //==========================================================================
    // Clock e sinais de entrada
    //==========================================================================

    reg clk;
    reg rst;
    reg ckp_in;

    //==========================================================================
    // Saídas do DUT (Device Under Test - Dispositivo em Teste)
    //==========================================================================

    wire tooth_rise;
    wire tooth_fall;

    //==========================================================================
    // Instância do módulo
    //==========================================================================

    edge_detector dut (
        .clk(clk),
        .rst(rst),
        .ckp_in(ckp_in),
        .tooth_rise(tooth_rise),
        .tooth_fall(tooth_fall)
    );

    //==========================================================================
    // Clock de 50 MHz
    // Período = 20 ns
    //==========================================================================

    initial begin
        clk = 1'b0;
        forever #10 clk = ~clk;
    end

    //==========================================================================
    // Geração dos estímulos
    //==========================================================================

    initial begin

        rst    = 1'b1;
        ckp_in = 1'b0;

        // Mantém reset ativo por alguns ciclos
        #100;
        rst = 1'b0;

        //----------------------------------------------------------------------
        // Primeira borda de subida
        //----------------------------------------------------------------------
        #80;
        ckp_in = 1'b1;

        //----------------------------------------------------------------------
        // Mantém nível alto
        //----------------------------------------------------------------------
        #200;

        //----------------------------------------------------------------------
        // Primeira borda de descida
        //----------------------------------------------------------------------
        ckp_in = 1'b0;

        //----------------------------------------------------------------------
        // Mantém nível baixo
        //----------------------------------------------------------------------
        #200;

        //----------------------------------------------------------------------
        // Segunda subida
        //----------------------------------------------------------------------
        ckp_in = 1'b1;
        #100;

        //----------------------------------------------------------------------
        // Segunda descida
        //----------------------------------------------------------------------
        ckp_in = 1'b0;
        #100;

        //----------------------------------------------------------------------
        // Pulsos rápidos
        //----------------------------------------------------------------------
        repeat (5) begin
            #40 ckp_in = 1'b1;
            #40 ckp_in = 1'b0;
        end

        //----------------------------------------------------------------------
        // Final da simulação
        //----------------------------------------------------------------------
        #200;
        $finish;

    end

    //==========================================================================
    // Monitor
    //==========================================================================

    initial begin

        $display(" Tempo | CKP | Rise | Fall");
        $display("--------------------------------");

        $monitor("%6t |  %b  |   %b   |   %b",
                 $time,
                 ckp_in,
                 tooth_rise,
                 tooth_fall);

    end

    //==========================================================================
    // Geração do arquivo VCD para GTKWave
    //==========================================================================

    initial begin
        $dumpfile("tb_edge_detector.vcd");
        $dumpvars(0, tb_edge_detector);
    end
endmodule